-- 0048 : เพิ่มชนิดเอกสาร "ใบสั่งขาย"
--
--  ไฟล์นี้มีคำสั่งเดียวโดยเจตนา ห้ามรวมกับ 0049
--
--  PostgreSQL เพิ่มค่าใหม่ให้ enum ในทรานแซกชันได้ก็จริง แต่ห้ามนำค่านั้น
--  ไปใช้ในทรานแซกชันเดียวกัน จะได้ error "unsafe use of new value"
--  ทั้ง SQL Editor ของ Supabase และไคลเอนต์ทั่วไปห่อทุกคำสั่งในไฟล์เดียว
--  ไว้ในทรานแซกชันเดียว จึงต้องแยกไฟล์ รันไฟล์นี้ให้จบก่อนแล้วค่อยรัน 0049
--
--  ทำไมต้องมีใบสั่งขาย : ฝั่งซื้อของเรามีครบตั้งแต่ใบขอซื้อ ใบสั่งซื้อ ใบรับของ
--  ถึงตั้งหนี้ แต่ฝั่งขายกระโดดจากใบเสนอราคาไปใบแจ้งหนี้เลย ธุรกิจที่รับออร์เดอร์
--  ล่วงหน้าแล้วทยอยส่งของจึงไม่มีเอกสารรองรับ และการจองสินค้าที่ทำไว้ใน 0041
--  ก็ไม่มีเอกสารต้นทางให้ผูก กลายเป็นจองลอย ๆ ที่ไม่รู้ว่าจองให้ออร์เดอร์ไหน
